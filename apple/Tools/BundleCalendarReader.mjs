// Rebuild the Apple resource with the same locked reader used by Windows (npm ci --prefix preview).
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const preview = new URL('../../preview/', import.meta.url);
const require = createRequire(new URL('package.json', preview));
await require('esbuild').build({
  entryPoints: [fileURLToPath(new URL('calendar-source.js', preview))],
  bundle: true, format: 'iife', platform: 'browser', target: 'safari17',
  banner: { js: '/* FRI calendar-source.js with ical.js (MPL-2.0). Generated by apple/Tools/BundleCalendarReader.mjs. */' },
  outfile: fileURLToPath(new URL('../Packages/FRICore/Sources/FRICore/Resources/calendar-reader.js', import.meta.url))
});

await require('esbuild').build({
  entryPoints: [fileURLToPath(new URL('ReadCalendarDocument.js', import.meta.url))],
  nodePaths: [fileURLToPath(new URL('node_modules', preview))],
  bundle: true, format: 'iife', globalName: 'FriDocument', target: 'safari17',
  outfile: fileURLToPath(new URL('../Packages/FRICore/Sources/FRICore/Resources/document-reader.js', import.meta.url))
});
const { writeFile } = await import('node:fs/promises');
await writeFile(new URL('../Packages/FRICore/Sources/FRICore/Resources/import-schema.json', import.meta.url),
  JSON.stringify(require('../desktop/ai-import.cjs').schema, null, 2) + '\n');
